class EquationStore:
    """Manages the catalog and lookup of discrete mathematical equations."""

    def __init__(self, equations: Optional[List[Equation]] = None):
        """Initialize equation catalog."""
        self.equations: Dict[str, Equation] = {}
        eq_list = equations if equations is not None else COMBINED_EQUATION_CATALOG
        for eq in eq_list:
            self.equations[eq.id] = eq

    def get_by_id(self, equation_id: str) -> Optional[Equation]:
        """Fetch equation by its unique ID."""
        return self.equations.get(equation_id)

    def get_by_course(self, course: str) -> List[Equation]:
        """Fetch all equations belonging to a specific course (e.g. 'MTH441', 'CS771', 'EE602')."""
        return [eq for eq in self.equations.values() if eq.course.upper() == course.upper()]

    def get_by_lecture(self, lecture: str, course: Optional[str] = None) -> List[Equation]:
        """Fetch all equations belonging to a specific lecture."""
        results = [eq for eq in self.equations.values() if eq.lecture == lecture]
        if course:
            results = [eq for eq in results if eq.course.upper() == course.upper()]
        return results

    def get_by_page(self, lecture: str, page: int, course: Optional[str] = None) -> List[Equation]:
        """Fetch all equations on a specific page of a lecture."""
        results = [
            eq
            for eq in self.equations.values()
            if eq.lecture == lecture and eq.page == page
        ]
        if course:
            results = [eq for eq in results if eq.course.upper() == course.upper()]
        return results

    def search_by_topic(self, topic: str, course: Optional[str] = None) -> List[Equation]:
        """Find equations related to a topic name."""
        topic_lower = topic.lower()
        results = [
            eq
            for eq in self.equations.values()
            if topic_lower in eq.topic.lower() or topic_lower in eq.name.lower()
        ]
        if course:
            results = [eq for eq in results if eq.course.upper() == course.upper()]
        return results

