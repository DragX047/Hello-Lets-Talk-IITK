"""Discrete Equation Catalog and Entity Extraction Module.

Decouples formal mathematical equations from raw body text chunks.
Maintains discrete equations as First-Class Entities with unique IDs,
LaTeX representations, variable definitions, and validity conditions.
"""

from dataclasses import asdict, dataclass
from typing import Any, Dict, List, Optional


@dataclass
class Equation:
    """Represents a discrete mathematical equation entity."""

    id: str
    name: str
    latex: str
    variables: List[str]
    conditions: str
    course: str
    lecture: str
    page: int
    topic: str
    description: str

    def to_dict(self) -> Dict[str, Any]:
        """Convert equation entity to dictionary."""
        return asdict(self)


